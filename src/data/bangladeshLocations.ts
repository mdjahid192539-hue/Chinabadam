export function formatTimeFromMinutes(totalMinutes: number): string {
  let mins = (totalMinutes + 1440) % 1440;
  let hours = Math.floor(mins / 60);
  let remainingMins = mins % 60;
  let period = hours >= 12 ? "PM" : "AM";

  let displayHours = hours % 12;
  if (displayHours === 0) displayHours = 12;

  let minsStr = remainingMins < 10 ? `0${remainingMins}` : `${remainingMins}`;
  
  // Convert digits to Bengali if needed or display formatted
  return `${displayHours}:${minsStr} ${period}`;
}
